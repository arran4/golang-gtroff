package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"os"
	"text/template"

	"github.com/arran4/golang-gtroff/internal/atomicfile"
)

type outputPaths struct{ macros, lines, catalogue, support string }
type generatedOutput = atomicfile.File

func run(args []string, stderr io.Writer) error {
	f := flag.NewFlagSet("gen", flag.ContinueOnError)
	f.SetOutput(stderr)
	paths := outputPaths{}
	f.StringVar(&paths.macros, "macrosloc", "macros.go", "Output file for macros")
	f.StringVar(&paths.lines, "parselineloc", "parseline.go", "Output file for parse line")
	f.StringVar(&paths.catalogue, "catalogueloc", "catalogue.go", "Output file for catalogue")
	f.StringVar(&paths.support, "supportloc", "docs/generated/catalogue-support.json", "Output file for syntax support report")
	check := f.Bool("check", false, "Compare generated bytes without writing or staging files")
	if err := f.Parse(args); err != nil {
		return err
	}
	if f.NArg() != 0 {
		return fmt.Errorf("unexpected generator arguments")
	}
	outputs, err := renderOutputs(inJson, goTemplates, paths)
	if err != nil {
		return err
	}
	if *check {
		return checkOutputs(outputs, os.ReadFile)
	}
	return atomicfile.WriteGenerated(outputs)
}

// Render all four outputs before touching their destinations. Inputs are explicit
// so tests can exercise malformed data/templates without editing embedded files.
func renderOutputs(raw []byte, source fs.FS, paths outputPaths) ([]generatedOutput, error) {
	cat, err := NormalizeCatalog(raw)
	if err != nil {
		return nil, err
	}
	templates, err := template.ParseFS(source, "*.template")
	if err != nil {
		return nil, fmt.Errorf("parse generator templates: %w", err)
	}
	macros, err := prepareMacrosData(cat)
	if err != nil {
		return nil, err
	}
	lines := prepareParselineData(cat, macros)
	report := buildSupportReport(cat, macros, lines)
	if report.Summary.UnexplainedGaps != 0 {
		return nil, fmt.Errorf("support plan has %d unexplained gaps", report.Summary.UnexplainedGaps)
	}
	jobs := []struct {
		template, path string
		model          any
	}{
		{"macros.go.template", paths.macros, macros},
		{"parseline.go.template", paths.lines, lines},
		{"catalogue.go.template", paths.catalogue, prepareCatalogueData(cat)},
	}
	var outputs []generatedOutput
	for _, job := range jobs {
		var buffer bytes.Buffer
		if err := templates.ExecuteTemplate(&buffer, job.template, job.model); err != nil {
			return nil, fmt.Errorf("render %s: %w", job.template, err)
		}
		formatted, err := format.Source(buffer.Bytes())
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", job.template, err)
		}
		outputs = append(outputs, generatedOutput{Path: job.path, Data: formatted})
	}
	reportJSON, err := report.JSON()
	if err != nil {
		return nil, err
	}
	return append(outputs, generatedOutput{Path: paths.support, Data: reportJSON}), nil
}

func checkOutputs(outputs []generatedOutput, readFile func(string) ([]byte, error)) error {
	for _, output := range outputs {
		data, err := readFile(output.Path)
		if err != nil {
			return fmt.Errorf("check generated %s: %w", output.Path, err)
		}
		if !bytes.Equal(data, output.Data) {
			return fmt.Errorf("stale generated file %s; run go generate ./...", output.Path)
		}
	}
	return nil
}
