func TestCoverageSummaryDetectsUnclassifiedEntry(t *testing.T) {
	cat, err := NormalizeCatalog(inJson)
	if err != nil {
		t.Fatal(err)
	}
	cat.Entries[0].Status = ""
	summary, err := cat.GenerateCoverageSummary()
	if err != nil {
		t.Fatal(err)
	}
	if got := summary.UnexplainedGaps; got != 1 {
		t.Fatalf("unclassified catalogue entry: gaps=%d, want 1", got)
	}
}

func TestSupportReportDetectsMissingAndAmbiguousPlan(t *testing.T) {
	for _, mode := range []string{"definition", "dispatch", "duplicate", "variant", "nil-entry"} {
		t.Run(mode, func(t *testing.T) {
			cat, err := NormalizeCatalog(inJson)
			if err != nil {
				t.Fatal(err)
			}
			macros, err := prepareMacrosData(cat)
			if err != nil {
				t.Fatal(err)
			}
			lines := prepareParselineData(cat, macros)
			want := supportMissing
			switch mode {
			case "definition":
				for i, d := range macros.Definitions {
					if d.Token == ".TH" {
						macros.Definitions = append(macros.Definitions[:i], macros.Definitions[i+1:]...)
						break
					}
				}
			case "dispatch", "duplicate", "variant":
				for i, d := range lines.Dispatches {
					if mode == "variant" && d.Command == ".SH" {
						lines.Dispatches[i].MsParser = d.DefaultParser
						want = supportAmbiguous
						break
					}
					if d.Command == ".TH" && mode != "variant" {
						if mode == "duplicate" {
							lines.Dispatches = append(lines.Dispatches, d)
							want = supportAmbiguous
						} else {
							lines.Dispatches = append(lines.Dispatches[:i], lines.Dispatches[i+1:]...)
						}
						break
					}
				}
			case "nil-entry":
				cat.Entries[0] = nil
			}
			report := buildSupportReport(cat, macros, lines)
			if report.Summary.UnexplainedGaps != 1 || report.Summary.EntriesByParseStatus[want] != 1 {
				t.Fatalf("missing/ambiguous implementation not detected: %+v", report.Summary)
			}
		})
	}
}

//go:embed testdata/catalogue/*.txtar
var supportCases embed.FS

func TestCatalogueScenarios(t *testing.T) {
	paths, err := fs.Glob(supportCases, "testdata/catalogue/*.txtar")
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range paths {
		t.Run(path, func(t *testing.T) {
			data, err := supportCases.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			files := map[string][]byte{}
			for _, f := range txtar.Parse(data).Files {
				if _, duplicate := files[f.Name]; duplicate {
					t.Fatalf("duplicate fixture %q", f.Name)
				}
				files[f.Name] = f.Data
			}
			input, ok := files["catalogue.json"]
			if !ok {
				t.Fatal("missing catalogue.json")
			}
			cat, err := NormalizeCatalog(input)
			if want := strings.TrimSpace(string(files["error.txt"])); want != "" {
				if err == nil || !strings.Contains(err.Error(), want) {
					t.Fatalf("want error containing %q, got %v", want, err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			macros, err := prepareMacrosData(cat)
			if err != nil {
				t.Fatal(err)
			}
			lines := prepareParselineData(cat, macros)
			report := buildSupportReport(cat, macros, lines)
			var got strings.Builder
			for _, entry := range report.Entries {
				fmt.Fprintf(&got, "%d %s %s %s %s %s %s\n", entry.Index, entry.Kind, entry.Package, entry.Token, entry.ParseStatus, entry.Parser, entry.Example)
			}
			if got.String() != string(files["expected.txt"]) || report.Summary.UnexplainedGaps != 0 {
				t.Fatalf("report:\n%s\nwant:\n%s\ngaps=%d", got.String(), files["expected.txt"], report.Summary.UnexplainedGaps)
			}
			// Newly declared commands must appear in syntactically valid generated
			// code through the templates, with no handwritten dispatcher edit.
			templates := template.Must(template.ParseFS(goTemplates, "*.template"))
			for name, model := range map[string]any{"macros.go.template": macros, "parseline.go.template": lines} {
				var generated bytes.Buffer
				if err := templates.ExecuteTemplate(&generated, name, model); err != nil {
					t.Fatal(err)
				}
				if _, err := parser.ParseFile(token.NewFileSet(), name, generated.Bytes(), parser.AllErrors); err != nil {
					t.Fatalf("new declarative entry generates invalid Go: %v", err)
				}
			}
		})
	}
}

func FuzzNormalizeCatalogue(f *testing.F) {
	f.Add([]byte(`[{"Contents":[{"Type":"Macro","Token":".NEW","Args":"[label]"}]}]`))
	f.Add([]byte(`[{"Contents":[{"Type":"invalid","Token":".bad"}]}]`))
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) > 16384 {
			return
		}
		cat, err := NormalizeCatalog(data)
		if err == nil {
			if err := cat.Validate(); err != nil {
				t.Fatalf("normalization returned an invalid catalogue: %v", err)
			}
		}
	})
}
