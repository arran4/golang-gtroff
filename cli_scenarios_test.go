//go:embed testdata/cli/*.txtar
var cliCases embed.FS
var updateCLI = flag.Bool("update-cli", false, "explicitly update CLI scenario goldens")

func TestCLIScenarios(t *testing.T) {
	var paths []string
	if err := fs.WalkDir(cliCases, "testdata/cli", func(p string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && strings.HasSuffix(p, ".txtar") {
			paths = append(paths, p)
		}
		return err
	}); err != nil {
		t.Fatal(err)
	}
	sort.Strings(paths)
	for _, path := range paths {
		path := path
		t.Run(strings.TrimPrefix(path, "testdata/cli/"), func(t *testing.T) {
			data, err := cliCases.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			ar := txtar.Parse(data)
			files := map[string][]byte{}
			virtual := fstest.MapFS{}
			for _, f := range ar.Files {
				if _, ok := files[f.Name]; ok {
					t.Fatalf("duplicate %s", f.Name)
				}
				files[f.Name] = f.Data
				if strings.HasPrefix(f.Name, "input/") {
					virtual[strings.TrimPrefix(f.Name, "input/")] = &fstest.MapFile{Data: f.Data}
				}
			}
			var args []string
			if err := json.Unmarshal(files["args.json"], &args); err != nil {
				t.Fatal(err)
			}
			run := func() (int, []byte, []byte) {
				var out, errOut bytes.Buffer
				code := cli.Run(args, cli.Environment{In: bytes.NewReader(files["stdin.1"]), Out: &out, Err: &errOut, Build: cli.BuildInfo{Version: "test", Commit: "abc123", Date: "2026-10-21"}, Open: func(path string) (io.ReadCloser, error) {
					f, e := virtual.Open(path)
					if e != nil {
						return nil, fs.ErrNotExist
					}
					return f, nil
				}, OpenRoot: func(path string) (manlib.Root, io.Closer, error) {
					sub, err := fs.Sub(virtual, path)
					if err != nil {
						return manlib.Root{}, nil, err
					}
					return manlib.Root{Label: "test", FS: sub}, nil, nil
				}})
				return code, out.Bytes(), errOut.Bytes()
			}
			code, out, errOut := run()
			code2, out2, errOut2 := run()
			if code != code2 || !bytes.Equal(out, out2) || !bytes.Equal(errOut, errOut2) {
				t.Fatal("CLI output is nondeterministic")
			}
			assertCLIJSON(t, args, files, virtual, out)
			outputs := []struct {
				name string
				data []byte
			}{{"stdout.txt", out}, {"stderr.txt", errOut}, {"exit.txt", []byte(strconv.Itoa(code) + "\n")}}
			if *updateCLI {
				for _, v := range outputs {
					found := false
					for i := range ar.Files {
						if ar.Files[i].Name == v.name {
							ar.Files[i].Data = v.data
							found = true
							break
						}
					}
					if !found {
						ar.Files = append(ar.Files, txtar.File{Name: v.name, Data: v.data})
					}
				}
				if err := os.WriteFile(path, txtar.Format(ar), 0644); err != nil {
					t.Fatal(err)
				}
			} else {
				for _, v := range outputs {
					want, ok := files[v.name]
					if !ok {
						t.Errorf("missing %s; update explicitly with -update-cli", v.name)
						continue
					}
					if !bytes.Equal(v.data, want) {
						t.Errorf("%s mismatch\ngot: %s\nwant: %s", v.name, v.data, want)
					}
				}
			}
		})
	}
}

// Golden JSON is generated by the actual CLI and cross-checked against a fresh
// parse of the same source. It is never a manually invented substitute AST.
func assertCLIJSON(t *testing.T, args []string, files map[string][]byte, virtual fstest.MapFS, out []byte) {
	t.Helper()
	if len(out) == 0 || out[0] != '{' {
		return
	}
	var doc struct {
		SchemaVersion int    `json:"schemaVersion"`
		Command       string `json:"command"`
		SourceName    string `json:"sourceName"`
		Source        string `json:"source"`
		Nodes         []struct {
			ID     groff.NodeID  `json:"id"`
			Parent groff.NodeID  `json:"parent"`
			Kind   groff.ASTKind `json:"kind"`
			Span   groff.Span    `json:"span"`
			Raw    string        `json:"raw"`
		} `json:"nodes"`
	}
	if err := json.Unmarshal(out, &doc); err != nil {
		t.Fatal(err)
	}
	if doc.SchemaVersion != 1 {
		t.Fatal("missing versioned schema")
	}
	// JSON re-encoding must be parseable without depending on key map iteration.
	var parsed interface{}
	if err := json.Unmarshal(out, &parsed); err != nil {
		t.Fatal(err)
	}
	encoded, err := json.Marshal(parsed)
	if err != nil || !json.Valid(encoded) {
		t.Fatal("JSON round-trip failed")
	}
	if doc.Command != "ast" {
		return
	}
	input := files["stdin.1"]
	if doc.SourceName != "<stdin>" {
		f, ok := virtual[doc.SourceName]
		if !ok {
			t.Fatal("unrecognized source")
		}
		input = f.Data
	}
	if doc.Source != string(input) {
		t.Fatal("AST source was canonicalized")
	}
	pkg := "man"
	for i, a := range args {
		if a == "--package" && i+1 < len(args) {
			pkg = args[i+1]
		}
	}
	tree, err := groff.ParseAST(bytes.NewReader(input), groff.WithPackage(pkg), groff.WithSourceName(doc.SourceName))
	if err != nil {
		t.Fatal(err)
	}
	var last groff.NodeID
	for _, row := range doc.Nodes {
		n := tree.Node(row.ID)
		if n == nil || row.ID <= last || row.Kind != n.Kind() || row.Raw != n.Raw() || row.Span != n.Span() {
			t.Fatalf("export differs from actual AST at node %d", row.ID)
		}
		last = row.ID
		if p := n.Parent(); p != nil && row.Parent != p.ID() {
			t.Fatal("source identity changed in selection")
		}
	}
	if len(doc.Nodes) == 0 {
		t.Fatal("AST export omitted all nodes")
	}
}
