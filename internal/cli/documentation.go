package cli

import (
	"bytes"
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/arran4/golang-gtroff/cmd"
	conversion "github.com/arran4/golang-gtroff/convert"
)

const manHelp = `Usage: gtroff man [COMMAND]
Write a deterministic man(7) page for gtroff or one command to stdout.
Uses the same help text as 'gtroff help COMMAND'; requires no groff executable.
`
const completionHelp = `Usage: gtroff completion bash|zsh|fish|powershell
Write shell completion source to stdout. Install it in your shell's completion
directory. Command and flag names come from the command help text.
`

// DocumentationCommands returns a fresh ordered list of documented commands.
func DocumentationCommands() []string {
	return []string{"validate", "ast", "render", "convert", "serve", "version", "man", "completion"}
}

// Man is a subcommand `gtroff man` Write a deterministic man(7) page for gtroff or one command to stdout
//
// Usage: gtroff man [COMMAND]
//
// Write a deterministic man(7) page for gtroff or one command to stdout.
// Uses the same help text as 'gtroff help COMMAND'; requires no groff executable.
//
// Flags:
//
//	commands: ... Document command name
func Man(commands ...string) error {
	code := manCommand(commands, getEnv())
	if code != ExitOK {
		return &cmd.ErrExitCode{Code: code}
	}
	return nil
}

// Completion is a subcommand `gtroff completion` Generate shell completions
//
// Usage: gtroff completion bash|zsh|fish|powershell
//
// Write shell completion source to stdout. Install it in your shell's completion
// directory. Command and flag names come from the command help text.
//
// Flags:
//
//	shell: ... Target shell: bash, zsh, fish, or powershell
func Completion(shell ...string) error {
	code := completionCommand(shell, getEnv())
	if code != ExitOK {
		return &cmd.ErrExitCode{Code: code}
	}
	return nil
}

func manCommand(args []string, e Environment) int {
	if len(args) > 1 {
		return usage(e, "man expects at most one command")
	}
	name, help := "gtroff", rootHelp
	if len(args) == 1 {
		if args[0] == "--help" || args[0] == "-h" {
			return writeString(e, manHelp)
		}
		var out bytes.Buffer
		code := commandHelp(Environment{Out: &out, Err: e.Err}, args[0])
		if code != 0 {
			return code
		}
		name += "-" + args[0]
		help = out.String()
	}
	var out strings.Builder
	fmt.Fprintf(&out, ".\\\" Generated from gtroff command help; do not edit.\n.TH %s 1 \"\" \"golang-gtroff\" \"User Commands\"\n.SH NAME\n%s\n.SH SYNOPSIS\n.nf\n", conversion.QuoteArgument(strings.ToUpper(name)), conversion.ProtectLine(name))
	for _, line := range strings.Split(strings.TrimSuffix(help, "\n"), "\n") {
		out.WriteString(conversion.ProtectLine(line) + "\n")
	}
	out.WriteString(".fi\n.SH SEE ALSO\n.MR man 7\n")
	return writeString(e, out.String())
}

var helpFlag = regexp.MustCompile(`--[a-z][a-z-]*`)

func completionCommand(args []string, e Environment) int {
	if len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
		return writeString(e, completionHelp)
	}
	if len(args) != 1 {
		return usage(e, "completion expects one shell")
	}
	commands := append(DocumentationCommands(), "help")
	flags := map[string][]string{}
	for _, command := range commands {
		var out bytes.Buffer
		if command == "help" {
			out.WriteString(rootHelp)
		} else {
			commandHelp(Environment{Out: &out}, command)
		}
		set := map[string]bool{"--help": true}
		for _, f := range helpFlag.FindAllString(out.String(), -1) {
			set[f] = true
		}
		if command == "render" || command == "convert" {
			set["-o"] = true
		}
		if command == "convert" {
			set["-i"] = true
		}
		for f := range set {
			flags[command] = append(flags[command], f)
		}
		sort.Strings(flags[command])
	}
	var out strings.Builder
	if args[0] == "zsh" {
		out.WriteString("#compdef gtroff\n")
	}
	out.WriteString("# Generated by gtroff completion; do not edit.\n")
	switch args[0] {
	case "bash":
		out.WriteString("_gtroff() {\n  local cur=\"${COMP_WORDS[COMP_CWORD]}\" words value\n  COMPREPLY=()\n  if (( COMP_CWORD == 1 )); then\n    words='" + strings.Join(commands, " ") + "'\n  else\n    case \"${COMP_WORDS[1]}\" in\n")
		for _, c := range commands {
			fmt.Fprintf(&out, "      %s) words='%s' ;;\n", c, strings.Join(flags[c], " "))
		}
		out.WriteString("    esac\n    if [[ $cur != -* ]]; then\n      while IFS= read -r value; do COMPREPLY+=(\"$value\"); done < <(compgen -f -- \"$cur\")\n      return\n    fi\n  fi\n  while IFS= read -r value; do COMPREPLY+=(\"$value\"); done < <(compgen -W \"$words\" -- \"$cur\")\n}\ncomplete -F _gtroff gtroff\n")
	case "zsh":
		out.WriteString("local -a candidates\nif (( CURRENT == 2 )); then\n  candidates=(" + strings.Join(commands, " ") + ")\n  compadd -- $candidates\nelse\n  case $words[2] in\n")
		for _, c := range commands {
			fmt.Fprintf(&out, "    %s) candidates=(%s) ;;\n", c, strings.Join(flags[c], " "))
		}
		out.WriteString("  esac\n  if [[ $PREFIX == -* ]]; then compadd -- $candidates; else _files; fi\nfi\n")
	case "fish":
		out.WriteString("complete -c gtroff -n '__fish_use_subcommand' -a '" + strings.Join(commands, " ") + "'\n")
		for _, c := range commands {
			for _, f := range flags[c] {
				if strings.HasPrefix(f, "--") {
					fmt.Fprintf(&out, "complete -c gtroff -n '__fish_seen_subcommand_from %s' -l %s\n", c, strings.TrimPrefix(f, "--"))
				}
			}
		}
	case "powershell":
		all := append([]string{}, commands...)
		seen := map[string]bool{}
		for _, c := range commands {
			for _, f := range flags[c] {
				if !seen[f] {
					all = append(all, f)
					seen[f] = true
				}
			}
		}
		out.WriteString("Register-ArgumentCompleter -Native -CommandName gtroff -ScriptBlock {\n  param($wordToComplete, $commandAst, $cursorPosition)\n  @('" + strings.Join(all, "', '") + "') | Where-Object { $_.StartsWith($wordToComplete) } | ForEach-Object {\n    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)\n  }\n}\n")
	default:
		return usage(e, "completion shell must be bash, zsh, fish or powershell")
	}
	return writeString(e, out.String())
}
